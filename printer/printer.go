var xpsMediaSizeNames = map[string]string{
	"a4":        "ISOA4",
	"a3":        "ISOA3",
	"a2":        "ISOA2",
	"a1":        "ISOA1",
	"a0":        "ISOA0",
	"a5":        "ISOA5",
	"a6":        "ISOA6",
	"letter":    "NorthAmericaLetter",
	"legal":     "NorthAmericaLegal",
	"tabloid":   "NorthAmericaTabloid",
	"statement": "NorthAmericaStatement",
}

func buildNativeXPSScript(targetPrinter, xpsPath string, geom DocumentGeometry, opts PrintOptions) string {
	mergedGeom := applyPrintOptionsToGeometry(geom, opts)

	var ticketLines []string
	switch strings.ToLower(strings.TrimSpace(mergedGeom.Orientation)) {
	case "landscape":
		ticketLines = append(ticketLines, `$ticket.PageOrientation = [System.Printing.PageOrientation]::Landscape`)
	case "portrait":
		ticketLines = append(ticketLines, `$ticket.PageOrientation = [System.Printing.PageOrientation]::Portrait`)
	}

	if mediaEnum, ok := xpsMediaSizeNames[strings.ToLower(strings.TrimSpace(mergedGeom.PaperName))]; ok {
		ticketLines = append(ticketLines, fmt.Sprintf(`$ticket.PageMediaSize = New-Object System.Printing.PageMediaSize([System.Printing.PageMediaSizeName]::%s)`, mediaEnum))
	}

	if opts.Copies > 1 {
		ticketLines = append(ticketLines, fmt.Sprintf(`$ticket.CopyCount = %d`, opts.Copies))
	}

	ticketConfig := ""
	if len(ticketLines) > 0 {
		ticketConfig = "    " + strings.Join(ticketLines, "\n    ") + "\n"
	}

	return fmt.Sprintf(`$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName ReachFramework, System.Printing
$ps = New-Object System.Printing.LocalPrintServer
$pq = $ps.GetPrintQueue('%s')
$writer = [System.Printing.PrintQueue]::CreateXpsDocumentWriter($pq)
$xpsDoc = $null
try {
    $xpsDoc = New-Object System.Windows.Xps.Packaging.XpsDocument('%s', [System.IO.FileAccess]::Read)
    $ticket = $pq.UserPrintTicket
    if (-not $ticket) { $ticket = $pq.DefaultPrintTicket }
    if ($ticket) { $ticket = $ticket.Clone() } else { $ticket = New-Object System.Printing.PrintTicket }
%s    $validatedRes = $pq.MergeAndValidatePrintTicket($pq.DefaultPrintTicket, $ticket)
    $writer.Write($xpsDoc.GetFixedDocumentSequence(), $validatedRes.ValidatedPrintTicket)
} finally {
    if ($xpsDoc) { $xpsDoc.Close() }
}
`, strings.ReplaceAll(targetPrinter, `'`, `''`),
		strings.ReplaceAll(xpsPath, `'`, `''`),
		ticketConfig)
}

var (
	xpsPrintTicketRelRe      = regexp.MustCompile(`(?is)<Relationship\b[^>]*\bType\s*=\s*"[^"]*/printticket"[^>]*/>`)
	xpsRelationshipTagRe     = regexp.MustCompile(`(?is)<Relationship\b[^>]*>`)
	xpsRelTypePrintTicketRe  = regexp.MustCompile(`(?is)\bType\s*=\s*"[^"]*/printticket"`)
	xpsRelTargetAttrRe       = regexp.MustCompile(`(?is)\bTarget\s*=\s*"([^"]+)"`)
	xpsOverridePrintTicketRe = regexp.MustCompile(`(?is)<Override\b[^>]*ContentType\s*=\s*"application/vnd\.ms-printing\.printticket\+xml"[^>]*/>`)
	xpsOverrideTagRe         = regexp.MustCompile(`(?is)<Override\b[^>]*>`)
	xpsContentTypePTRe       = regexp.MustCompile(`(?is)\bContentType\s*=\s*"application/vnd\.ms-printing\.printticket\+xml"`)
	xpsPartNameAttrRe        = regexp.MustCompile(`(?is)\bPartName\s*=\s*"([^"]+)"`)
)

func printNativeXPSWithOptions(ctx context.Context, targetPrinter, filePath string, geom DocumentGeometry, opts PrintOptions) ([]byte, error) {
	xpsPath := filePath
	cleaned, cleanErr := sanitizeXPSForNativePrint(filePath)
	if cleanErr != nil {
		isOpenXPS := strings.EqualFold(filepath.Ext(filePath), ".oxps") ||
			geom.Format == ".oxps" ||
			detectZIPSpoolFormatFromFile(filePath) == ".oxps"
		if isOpenXPS {
			return nil, fmt.Errorf("failed to convert OpenXPS (.oxps) for native Windows printing: %w", cleanErr)
		}
		log.Printf("[Printer] Warning sanitizing XPS PrintTickets for %s: %v; printing original XPS", filepath.Base(filePath), cleanErr)
	} else if cleaned != "" {
		xpsPath = cleaned
		defer os.Remove(cleaned)
	}

	psScript := buildNativeXPSScript(targetPrinter, xpsPath, geom, opts)
	cmd := exec.CommandContext(ctx, "powershell", "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-Command", psScript)
	hideCmd(cmd)
	return cmd.CombinedOutput()
}

// convertOXPStoXPS converts an OpenXPS (ECMA-388) or XPS container into a clean Microsoft XPS
// (2005/06) container with embedded source PrintTickets stripped so target printer tickets and
// DPI transforms apply cleanly without cross-driver DEVMODE/DPI mismatches.
func convertOXPStoXPS(oxpsPath string) (string, error) {
	return sanitizeXPSForNativePrint(oxpsPath)
}

func resolveXPSRelationshipTarget(relsEntryName, target string) string {
	cleanTarget := strings.TrimSpace(strings.ReplaceAll(target, "\\", "/"))
	if cleanTarget == "" {
		return ""
	}
	if strings.HasPrefix(cleanTarget, "/") {
		return strings.ToLower(strings.TrimPrefix(path.Clean(cleanTarget), "/"))
	}
	ownerDir := path.Dir(strings.ReplaceAll(relsEntryName, "\\", "/"))
	if strings.HasSuffix(strings.ToLower(ownerDir), "/_rels") {
		ownerDir = path.Dir(ownerDir)
	} else if strings.EqualFold(ownerDir, "_rels") {
		ownerDir = "."
	}
	resolved := path.Clean(path.Join(ownerDir, cleanTarget))
	return strings.ToLower(strings.TrimPrefix(resolved, "/"))
}

func isSourcePrintTicketPart(entryName string, ptParts map[string]struct{}) bool {
	norm := strings.ToLower(strings.TrimPrefix(strings.ReplaceAll(entryName, "\\", "/"), "/"))
	if _, ok := ptParts[norm]; ok {
		return true
	}
	base := path.Base(norm)
	return strings.HasSuffix(base, "_pt.xml") || base == "mxdc_empty_pt.xml"
}

func sanitizeXPSForNativePrint(xpsOrOxpsPath string) (string, error) {
	zr, err := zip.OpenReader(xpsOrOxpsPath)
	if err != nil {
		return "", err
	}
	defer zr.Close()

	// Collect PrintTicket part paths declared in .rels and [Content_Types].xml before rewriting
	// so embedded MXDW PageDevmodeSnapshot / 600-DPI PrintTickets are never cloned onto Device 2.
	ptParts := make(map[string]struct{})
	for _, f := range zr.File {
		lower := strings.ToLower(strings.ReplaceAll(f.Name, "\\", "/"))
		if !strings.HasSuffix(lower, ".rels") && lower != "[content_types].xml" {
			continue
		}
		rc, openErr := f.Open()
		if openErr != nil {
			return "", openErr
		}
		data, readErr := io.ReadAll(rc)
		_ = rc.Close()
		if readErr != nil {
			return "", readErr
		}
		if strings.HasSuffix(lower, ".rels") {
			for _, tag := range xpsRelationshipTagRe.FindAll(data, -1) {
				if !xpsRelTypePrintTicketRe.Match(tag) {
					continue
				}
				if m := xpsRelTargetAttrRe.FindSubmatch(tag); len(m) == 2 {
					if target := resolveXPSRelationshipTarget(f.Name, string(m[1])); target != "" {
						ptParts[target] = struct{}{}
					}
				}
			}
		} else {
			for _, tag := range xpsOverrideTagRe.FindAll(data, -1) {
				if !xpsContentTypePTRe.Match(tag) {
					continue
				}
				if m := xpsPartNameAttrRe.FindSubmatch(tag); len(m) == 2 {
					part := strings.ToLower(strings.TrimPrefix(path.Clean(strings.ReplaceAll(string(m[1]), "\\", "/")), "/"))
					if part != "" {
						ptParts[part] = struct{}{}
					}
				}
			}
		}
	}

	tmpFile, err := os.CreateTemp("", "bridge_xps_clean_*.xps")
	if err != nil {
		return "", err
	}
	tmpPath := tmpFile.Name()

	zw := zip.NewWriter(tmpFile)
	writeErr := func() error {
		for _, f := range zr.File {
			if isSourcePrintTicketPart(f.Name, ptParts) {
				continue
			}

			rc, openErr := f.Open()
			if openErr != nil {
				return openErr
			}
			data, readErr := io.ReadAll(rc)
			_ = rc.Close()
			if readErr != nil {
				return readErr
			}

			lower := strings.ToLower(f.Name)
			if strings.HasSuffix(lower, ".xml") ||
				strings.HasSuffix(lower, ".rels") ||
				strings.HasSuffix(lower, ".fdseq") ||
				strings.HasSuffix(lower, ".fdoc") ||
				strings.HasSuffix(lower, ".fpage") {
				data = bytes.ReplaceAll(data, []byte("http://schemas.openxps.org/oxps/v1.0"), []byte("http://schemas.microsoft.com/xps/2005/06"))
				data = bytes.ReplaceAll(data, []byte("application/oxps"), []byte("application/vnd.ms-package.xps-fixeddocumentsequence+xml"))
			}
			if strings.HasSuffix(lower, ".rels") {
				data = xpsPrintTicketRelRe.ReplaceAll(data, nil)
			} else if strings.EqualFold(strings.ReplaceAll(f.Name, "\\", "/"), "[Content_Types].xml") {
				data = xpsOverridePrintTicketRe.ReplaceAll(data, nil)
			}

			hdr := f.FileHeader
			hdr.CompressedSize = 0
			hdr.CompressedSize64 = 0
			hdr.UncompressedSize = 0
			hdr.UncompressedSize64 = 0
			hdr.CRC32 = 0
			w, createErr := zw.CreateHeader(&hdr)
			if createErr != nil {
				return createErr
			}
			if _, wErr := w.Write(data); wErr != nil {
				return wErr
			}
		}
		return nil
	}()

	closeZipErr := zw.Close()
	closeFileErr := tmpFile.Close()
	if writeErr != nil || closeZipErr != nil || closeFileErr != nil {
		_ = os.Remove(tmpPath)
		if writeErr != nil {
			return "", writeErr
		}
		if closeZipErr != nil {
			return "", closeZipErr
		}
		return "", closeFileErr
	}
	return tmpPath, nil
}

// --- Print Watcher (Watches C:\Bridge\Print to send jobs to peer) ---

// PrintWatcher monitors C:\Bridge\Print and pushes files to peer.
type PrintWatcher struct {
	printDir          string
	sentDir           string
	peerURL           string
	authToken         string
	client            *http.Client
	ctx               context.Context
	cancel            context.CancelFunc
	wg                sync.WaitGroup
	inFlightMu        sync.Mutex
	inFlight          map[string]bool
	OnUploadStarted   func(fileName string)
	OnUploadCompleted func(fileName string)
	OnUploadFailed    func(fileName string, err error)
}

// NewPrintWatcher creates a new print watcher.
func NewPrintWatcher(printDir, sentDir, peerURL, authToken string) *PrintWatcher {
	ctx, cancel := context.WithCancel(context.Background())
	return &PrintWatcher{
		printDir:  filepath.Clean(printDir),
		sentDir:   filepath.Clean(sentDir),
		peerURL:   strings.TrimRight(peerURL, "/"),
		authToken: authToken,
		client: &http.Client{
			Timeout: 60 * time.Second,
		},
		ctx:      ctx,
		cancel:   cancel,
		inFlight: make(map[string]bool),
	}
}

// UpdatePeerURL dynamically updates the destination peer URL.
func (pw *PrintWatcher) UpdatePeerURL(peerURL string) {
	clean := strings.TrimRight(strings.TrimSpace(peerURL), "/")
	if clean == "" {
		return
	}
	pw.inFlightMu.Lock()
	if pw.peerURL != clean {
		log.Printf("[PrintWatcher] Peer URL updated to: %s", clean)
		pw.peerURL = clean
	}
	pw.inFlightMu.Unlock()
}

// Start begins watching the print directory.
func (pw *PrintWatcher) Start() error {
	if err := os.MkdirAll(pw.printDir, 0755); err != nil {
		return fmt.Errorf("failed to create print directory: %w", err)
	}
	if err := os.MkdirAll(pw.sentDir, 0755); err != nil {
		return fmt.Errorf("failed to create print sent directory: %w", err)
	}

	watcher, err := fsnotify.NewWatcher()
	if err != nil {
		return fmt.Errorf("failed to create print fsnotify watcher: %w", err)
	}

	if err := watcher.Add(pw.printDir); err != nil {
		watcher.Close()
		return fmt.Errorf("failed to watch print directory: %w", err)
	}

	pw.wg.Add(1)
	go pw.watchLoop(watcher)

	pw.wg.Add(1)
	go pw.scanLoop()

	log.Printf("[PrintWatcher] Started watching %s (peer: %s)", pw.printDir, pw.peerURL)
	return nil
}

// Stop shuts down the print watcher.
func (pw *PrintWatcher) Stop() {
	pw.cancel()
	pw.wg.Wait()
	log.Printf("[PrintWatcher] Stopped.")
}

func (pw *PrintWatcher) watchLoop(watcher *fsnotify.Watcher) {
	defer pw.wg.Done()
	defer watcher.Close()

	for {
		select {
		case <-pw.ctx.Done():
			return
		case event, ok := <-watcher.Events:
			if !ok {
				return
			}
			if event.Has(fsnotify.Create) || event.Has(fsnotify.Write) {
				if pw.isIgnored(event.Name) {
					continue
				}
				go pw.processFile(event.Name)
			}
		case err, ok := <-watcher.Errors:
			if !ok {
				return
			}
			log.Printf("[PrintWatcher] Watcher error: %v", err)
		}
	}
}

func (pw *PrintWatcher) scanLoop() {
	defer pw.wg.Done()
	ticker := time.NewTicker(15 * time.Second)
	defer ticker.Stop()

	// Initial scan
	select {
	case <-time.After(500 * time.Millisecond):
		pw.scanDir()
	case <-pw.ctx.Done():
		return
	}

	for {
		select {
		case <-pw.ctx.Done():
			return
		case <-ticker.C:
			pw.scanDir()
		}
	}
}

func (pw *PrintWatcher) scanDir() {
	entries, err := os.ReadDir(pw.printDir)
	if err != nil {
		return
	}
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		path := filepath.Join(pw.printDir, entry.Name())
		if pw.isIgnored(path) {
			continue
		}
		go pw.processFile(path)
	}
}

func (pw *PrintWatcher) isIgnored(path string) bool {
	base := filepath.Base(path)
	if strings.HasPrefix(base, ".") || strings.HasSuffix(base, ".part") || strings.HasSuffix(base, ".tmp") {
		return true
	}
	clean := filepath.Clean(path)
	if strings.HasPrefix(clean, pw.sentDir) {
		return true
	}
	return false
}

func (pw *PrintWatcher) processFile(fullPath string) {
	pw.inFlightMu.Lock()
	if pw.inFlight[fullPath] {
		pw.inFlightMu.Unlock()
		return
	}
	pw.inFlight[fullPath] = true
	pw.inFlightMu.Unlock()

	defer func() {
		pw.inFlightMu.Lock()
		delete(pw.inFlight, fullPath)
		pw.inFlightMu.Unlock()
	}()

	// Stabilization check: wait 500ms
	const checkInterval = 500 * time.Millisecond
	var lastSize int64 = -1
	deadline := time.Now().Add(60 * time.Second)

	for {
		select {
		case <-pw.ctx.Done():
			return
		default:
		}

		if time.Now().After(deadline) {
			log.Printf("[PrintWatcher] Timeout stabilizing %s", fullPath)
			return
		}

		info, err := os.Stat(fullPath)
		if err != nil {
			return // file vanished
		}

		f, err := os.Open(fullPath)
		if err != nil {
			time.Sleep(200 * time.Millisecond)
			continue
		}
		_ = f.Close()

		if lastSize != -1 && info.Size() == lastSize {
			break
		}
		lastSize = info.Size()
		time.Sleep(checkInterval)
	}

	pw.sendWithRetry(fullPath)
}

func (pw *PrintWatcher) sendWithRetry(fullPath string) {
	backoffSteps := []time.Duration{
		2 * time.Second,
		5 * time.Second,
		15 * time.Second,
		30 * time.Second,
	}
	backoffIdx := 0
	fileName := filepath.Base(fullPath)

	if pw.OnUploadStarted != nil {
		pw.OnUploadStarted(fileName)
	}

	for {
		select {
		case <-pw.ctx.Done():
			return
		default:
		}

		err := pw.uploadPrintJob(fileName, fullPath)
		if err == nil {
			log.Printf("[PrintWatcher] Successfully dispatched print job for %s", fileName)
			pw.moveToSent(fullPath, fileName)
			if pw.OnUploadCompleted != nil {
				pw.OnUploadCompleted(fileName)
			}
			return
		}

		delay := backoffSteps[backoffIdx]
		if backoffIdx < len(backoffSteps)-1 {
			backoffIdx++
		}

		log.Printf("[PrintWatcher] Failed to send print job %s: %v. Retrying in %v...", fileName, err, delay)
		if pw.OnUploadFailed != nil {
			pw.OnUploadFailed(fileName, err)
		}

		select {
		case <-pw.ctx.Done():
			return
		case <-time.After(delay):
		}

		if _, err := os.Stat(fullPath); err != nil {
			return // file no longer exists
		}
	}
}

func (pw *PrintWatcher) uploadPrintJob(fileName, fullPath string) error {
	pw.inFlightMu.Lock()
	peer := pw.peerURL
	pw.inFlightMu.Unlock()

	if peer == "" {
		return errors.New("peer URL not configured yet")
	}

	f, err := os.Open(fullPath)
	if err != nil {
		return err
	}
	defer f.Close()

	destURL := fmt.Sprintf("%s/api/print", peer)
	req, err := http.NewRequestWithContext(pw.ctx, "POST", destURL, f)
	if err != nil {
		return err
	}

	req.Header.Set("X-Bridge-Token", pw.authToken)
	req.Header.Set("X-Bridge-FileName", fileName)
	req.Header.Set("Content-Type", "application/octet-stream")

	resp, err := pw.client.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		body, _ := io.ReadAll(io.LimitReader(resp.Body, 512))
		return fmt.Errorf("peer returned HTTP %d: %s", resp.StatusCode, string(body))
	}

	return nil
}

func (pw *PrintWatcher) moveToSent(fullPath, fileName string) {
	destPath := filepath.Join(pw.sentDir, fileName)
	if _, err := os.Stat(destPath); err == nil {
		ext := filepath.Ext(fileName)
		raw := strings.TrimSuffix(fileName, ext)
		destPath = filepath.Join(pw.sentDir, fmt.Sprintf("%s_%d%s", raw, time.Now().Unix(), ext))
	}

	if err := os.Rename(fullPath, destPath); err != nil {
		log.Printf("[PrintWatcher] Warning: failed to move %s to Sent: %v", fullPath, err)
	}
}

func validatePeerHTTPURL(peerURL string) (string, error) {
	trimmed := strings.TrimSpace(peerURL)
	if trimmed == "" {
		return "", errors.New("invalid peer URL: peer PC is not connected yet (blank URL)")
	}
	if strings.ContainsAny(trimmed, " \t\r\n") {
		return "", fmt.Errorf("invalid peer URL %q: contains whitespace", peerURL)
	}
	cleanPeer := strings.TrimRight(trimmed, "/")
	if cleanPeer == "" {
		return "", errors.New("invalid peer URL: peer PC is not connected yet (blank URL)")
	}
	u, err := url.Parse(cleanPeer)
	if err != nil {
		return "", fmt.Errorf("invalid peer URL %q: %w", peerURL, err)
	}
	scheme := strings.ToLower(u.Scheme)
	if scheme != "http" && scheme != "https" {
		return "", fmt.Errorf("invalid peer URL %q: unsupported scheme %q (expected http or https)", peerURL, u.Scheme)
	}
	if u.Hostname() == "" {
		return "", fmt.Errorf("invalid peer URL %q: missing host", peerURL)
	}
	if p := u.Port(); p != "" {
		portNum, convErr := strconv.Atoi(p)
		if convErr != nil || portNum < 1 || portNum > 65535 {
			return "", fmt.Errorf("invalid peer URL %q: invalid port %q", peerURL, p)
		}
	}
	if u.RawQuery != "" || u.Fragment != "" {
		return "", fmt.Errorf("invalid peer URL %q: query parameters and fragments are not allowed", peerURL)
	}
	u.Scheme = scheme
	return strings.TrimRight(u.String(), "/"), nil
}

// SendDirectPrint directly uploads a document file to the peer's print endpoint.
// Optional key-value header pairs (e.g. "X-Bridge-Node-Name", nodeName) can be provided.
func SendDirectPrint(ctx context.Context, peerURL, authToken, filePath string, extraHeaders ...string) error {
	return SendDirectPrintWithOptions(ctx, peerURL, authToken, filePath, PrintOptions{}, extraHeaders...)
}

// SendDirectPrintWithOptions uploads a document file with explicit PrintOptions metadata to the peer's print endpoint.
func SendDirectPrintWithOptions(ctx context.Context, peerURL, authToken, filePath string, opts PrintOptions, extraHeaders ...string) error {
	cleanPeer, err := validatePeerHTTPURL(peerURL)
	if err != nil {
		return err
	}
	if ctx == nil {
		ctx = context.Background()
	}

	if err := ValidatePrintableFormat(filePath); err != nil {
		return err
	}

	f, err := os.Open(filePath)
	if err != nil {
		return fmt.Errorf("failed to open file %s: %w", filePath, err)
	}
	defer f.Close()

	destURL := fmt.Sprintf("%s/api/print", cleanPeer)
	req, err := http.NewRequestWithContext(ctx, "POST", destURL, f)
	if err != nil {
		return err
	}

	req.Header.Set("X-Bridge-Token", authToken)
	req.Header.Set("X-Bridge-FileName", filepath.Base(filePath))
	req.Header.Set("Content-Type", "application/octet-stream")

	// Pre-inspect geometry and apply any explicit overrides
	geom := applyPrintOptionsToGeometry(DetectDocumentGeometry(filePath), opts)
	if geom.PaperName != "" {
		req.Header.Set("X-Bridge-Paper-Size", geom.PaperName)
	}
	if geom.Orientation != "" {
		req.Header.Set("X-Bridge-Orientation", geom.Orientation)
	}
	if geom.PageCount > 0 {
		req.Header.Set("X-Bridge-Page-Count", fmt.Sprintf("%d", geom.PageCount))
	}
	if opts.Copies > 1 {
		req.Header.Set("X-Bridge-Copies", fmt.Sprintf("%d", opts.Copies))
	}
	if opts.Color != nil {
		if *opts.Color {
			req.Header.Set("X-Bridge-Color", "color")
		} else {
			req.Header.Set("X-Bridge-Color", "monochrome")
		}
	}

	for i := 0; i+1 < len(extraHeaders); i += 2 {
		req.Header.Set(extraHeaders[i], extraHeaders[i+1])
	}

	if req.Header.Get("X-Bridge-Origin") == "" {
		if node := req.Header.Get("X-Bridge-Node-Name"); node != "" {
			req.Header.Set("X-Bridge-Origin", node)
		}
	}

	resp, err := directPrintClient.Do(req)
	if err != nil {
		return fmt.Errorf("failed to deliver print job: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode != http.StatusOK {
		body, _ := io.ReadAll(io.LimitReader(resp.Body, 512))
		return fmt.Errorf("peer returned HTTP %d: %s", resp.StatusCode, string(body))
	}

	return nil
}
