func isSupportedPrintableExt(ext string) bool {
	switch strings.ToLower(strings.TrimSpace(ext)) {
	case ".pdf", ".xps", ".oxps", ".png", ".jpg", ".jpeg", ".tif", ".tiff", ".gif", ".bmp":
		return true
	default:
		return false
	}
}

// ValidatePrintableFormat checks whether filePath is a supported format for direct printing
// (PDF, XPS, OpenXPS, or standard raster images) and returns an actionable error for raw
// printer spool streams (.ps/.pcl/.emf/.bin) or office/text documents (.docx/.txt) sent via SendTo.
func ValidatePrintableFormat(filePath string) error {
	fi, err := os.Stat(filePath)
	if err != nil {
		return fmt.Errorf("failed to access print file %s: %w", filePath, err)
	}
	if fi.IsDir() {
		return fmt.Errorf("print target %s is a directory, expected a file", filePath)
	}

	ext := strings.ToLower(filepath.Ext(filePath))

	// Reject explicit non-printable document/archive extensions (e.g. .docx/.xlsx are PK\x03\x04 ZIPs)
	// while still inspecting generic spool extensions (.prn/.spl/.bin/.raw/.dat/.tmp) by magic bytes.
	if ext != "" && !isSupportedPrintableExt(ext) && !isGenericSpoolExt(ext) && ext != ".tmp" {
		switch ext {
		case ".ps", ".pcl", ".emf":
			return fmt.Errorf("unsupported raw printer spool format (%s) for %s: Bridge requires PDF, XPS/OpenXPS, or image input", ext, filepath.Base(filePath))
		default:
			return fmt.Errorf("unsupported file format (%s) for direct printing (%s): only PDF, XPS/OpenXPS, and images (PNG/JPG/BMP/TIFF/GIF) are supported directly; for Word/Excel/web documents use Ctrl+P -> 'Print on <Device>'", ext, filepath.Base(filePath))
		}
	}

	f, err := os.Open(filePath)
	if err == nil {
		var hdr [4096]byte
		n, _ := f.Read(hdr[:])
		_ = f.Close()
		if n > 0 {
			detected := DetectSpoolFormat(hdr[:n])
			switch detected {
			case ".ps":
				return fmt.Errorf("unsupported PostScript (.ps) spool stream for %s: Bridge requires PDF, XPS/OpenXPS, or image input; configure the virtual printer to use an XPS/OpenXPS driver", filepath.Base(filePath))
			case ".pcl":
				return fmt.Errorf("unsupported PCL/PJL (.pcl) spool stream for %s: Bridge requires PDF, XPS/OpenXPS, or image input; configure the virtual printer to use an XPS/OpenXPS driver", filepath.Base(filePath))
			case ".emf":
				return fmt.Errorf("unsupported Windows EMF (.emf) spool stream for %s: Bridge requires PDF, XPS/OpenXPS, or image input; configure the virtual printer to use an XPS/OpenXPS driver", filepath.Base(filePath))
			case ".pdf", ".xps", ".oxps", ".png", ".jpg", ".gif", ".bmp", ".tif":
				return nil
			}
		}
	}

	if isSupportedPrintableExt(ext) {
		return nil
	}

	switch ext {
	case ".ps", ".pcl", ".emf", ".bin", ".raw", ".prn", ".spl":
		return fmt.Errorf("unsupported raw printer spool format (%s) for %s: Bridge requires PDF, XPS/OpenXPS, or image input", ext, filepath.Base(filePath))
	case "":
		return fmt.Errorf("unrecognized binary print stream for %s (no file extension or PDF/XPS/image signature): cannot print directly", filepath.Base(filePath))
	default:
		return fmt.Errorf("unsupported file format (%s) for direct printing (%s): only PDF, XPS/OpenXPS, and images (PNG/JPG/BMP/TIFF/GIF) are supported directly; for Word/Excel/web documents use Ctrl+P -> 'Print on <Device>'", ext, filepath.Base(filePath))
	}
}

// PrintFile silently prints filePath to targetPrinter using auto-detected document geometry.
func PrintFile(filePath, targetPrinter string) error {
	return PrintFileWithOptions(filePath, targetPrinter, PrintOptions{})
}

// PrintFileWithOptions silently prints filePath to targetPrinter, applying PrintOptions overrides
// (PaperSize, Orientation, Copies, Color, etc.) on top of auto-detected document geometry.
func PrintFileWithOptions(filePath, targetPrinter string, opts PrintOptions) error {
	if err := ValidatePrintableFormat(filePath); err != nil {
		return err
	}

	sumatraBin := strings.TrimSpace(opts.SumatraPath)
	resolvedPrinter := strings.TrimSpace(targetPrinter)
	if resolvedPrinter == "" {
		var err error
		resolvedPrinter, err = GetTargetPhysicalPrinter()
		if err != nil {
			if strings.Contains(strings.ToLower(sumatraBin), "mock") {
				resolvedPrinter = "MockPrinter"
			} else {
				return fmt.Errorf("no physical printer available: %w", err)
			}
		}
	}

	if !isUsableSumatra(sumatraBin) {
		if found := FindSumatraPDF(); isUsableSumatra(found) {
			sumatraBin = found
		}
	}

	timeout := opts.Timeout
	if timeout <= 0 {
		timeout = 60 * time.Second
	}
	ctx, cancel := context.WithTimeout(context.Background(), timeout)
	defer cancel()

	geom := DetectDocumentGeometry(filePath)
	out, err := executePrint(ctx, sumatraBin, resolvedPrinter, filePath, geom, opts)
	if err != nil {
		if trimmed := strings.TrimSpace(string(out)); trimmed != "" {
			return fmt.Errorf("%w (%s)", err, trimmed)
		}
		return err
	}
	return nil
}

func isXPSFile(filePath string, geom DocumentGeometry) bool {
	ext := strings.ToLower(filepath.Ext(filePath))
	if ext == ".xps" || ext == ".oxps" {
		return true
	}
	return geom.Format == ".xps" || geom.Format == ".oxps"
}

type sumatraPrintRunner func(ctx context.Context, sumatraBin, targetPrinter, printSettings, filePath string) ([]byte, error)
type nativeXPSPrintRunner func(ctx context.Context, targetPrinter, filePath string, geom DocumentGeometry, opts PrintOptions) ([]byte, error)

func isMockSumatraPath(p string) bool {
	return strings.Contains(strings.ToLower(p), "mock")
}

func runSumatraCommand(ctx context.Context, sumatraBin, targetPrinter, printSettings, filePath string) ([]byte, error) {
	cmd := exec.CommandContext(ctx, sumatraBin, "-print-to", targetPrinter, "-silent", "-print-settings", printSettings, "-exit-when-done", filePath)
	hideCmd(cmd)
	return cmd.CombinedOutput()
}

func executePrint(ctx context.Context, sumatraBin, targetPrinter, filePath string, geom DocumentGeometry, opts PrintOptions) ([]byte, error) {
	return executePrintWithRunners(ctx, runtime.GOOS, sumatraBin, targetPrinter, filePath, geom, opts, runSumatraCommand, printNativeXPSWithOptions)
}

func executePrintWithRunners(
	ctx context.Context,
	goos string,
	sumatraBin, targetPrinter, filePath string,
	geom DocumentGeometry,
	opts PrintOptions,
	sumatraRunner sumatraPrintRunner,
	nativeRunner nativeXPSPrintRunner,
) ([]byte, error) {
	mergedGeom := applyPrintOptionsToGeometry(geom, opts)
	printSettings := BuildPrintSettingsWithOptions(geom, opts)
	isXPS := isXPSFile(filePath, mergedGeom)
	usableSumatra := isUsableSumatra(sumatraBin)
	isMock := isMockSumatraPath(sumatraBin)

	// On Windows, route .xps/.oxps natively through ReachFramework/System.Printing FIRST
	// (unless using a mock Sumatra binary in tests) to avoid SumatraPDF OXPS scaling regressions.
	if goos == "windows" && isXPS && !isMock {
		log.Printf("[Printer] Printing %s natively via Windows XPS/OXPS to '%s' (paper: %s, orientation: %s)...",
			filepath.Base(filePath), targetPrinter, mergedGeom.PaperName, mergedGeom.Orientation)
		out, err := nativeRunner(ctx, targetPrinter, filePath, mergedGeom, opts)
		if err == nil {
			return out, nil
		}
		if ctx.Err() == nil && usableSumatra {
			log.Printf("[Printer] Native Windows XPS/OXPS print returned error (%v) for '%s'; falling back to SumatraPDF (settings: %s)...",
				err, targetPrinter, printSettings)
			return sumatraRunner(ctx, sumatraBin, targetPrinter, printSettings, filePath)
		}
		return out, err
	}

	if usableSumatra {
		log.Printf("[Printer] Printing %s via SumatraPDF to '%s' (settings: %s)...", filepath.Base(filePath), targetPrinter, printSettings)
		out, err := sumatraRunner(ctx, sumatraBin, targetPrinter, printSettings, filePath)
		if err != nil && ctx.Err() == nil && isXPS && !isMock {
			log.Printf("[Printer] SumatraPDF returned error (%v) for '%s'; attempting native Windows XPS/OXPS fallback...", err, targetPrinter)
			return nativeRunner(ctx, targetPrinter, filePath, mergedGeom, opts)
		}
		return out, err
	}

	if isXPS {
		log.Printf("[Printer] SumatraPDF not found; printing %s via native Windows XPS/OXPS to '%s' (paper: %s, orientation: %s)...",
			filepath.Base(filePath), targetPrinter, mergedGeom.PaperName, mergedGeom.Orientation)
		return nativeRunner(ctx, targetPrinter, filePath, mergedGeom, opts)
	}

	return nil, fmt.Errorf("silent print engine (SumatraPDF) is missing on host; run setup or install to auto-provision")
}

func (ps *PrintService) processJob(job PrintJob) {
	log.Printf("[Printer] Processing job %s (%s)...", job.ID, job.FileName)
	if ps.OnJobStarted != nil {
		ps.OnJobStarted(job)
	}

	if err := ValidatePrintableFormat(job.FilePath); err != nil {
		log.Printf("[Printer] ERROR: Job %s (%s) rejected: %v", job.ID, job.FileName, err)
		ps.failJob(job, err.Error())
		return
	}

	targetPrinter := strings.TrimSpace(ps.getTargetPrinter())
	sumatraBin := ps.getSumatraPath()
	var err error
	if targetPrinter == "" {
		if ps.resolveTargetPrinter != nil {
			targetPrinter, err = ps.resolveTargetPrinter()
		} else {
			targetPrinter, err = GetTargetPhysicalPrinter()
			if err != nil && strings.Contains(strings.ToLower(sumatraBin), "mock") {
				targetPrinter = "MockPrinter"
				err = nil
			}
		}
		targetPrinter = strings.TrimSpace(targetPrinter)
	}

	if err != nil || targetPrinter == "" {
		reason := "no physical printer available"
		if err != nil {
			reason = fmt.Sprintf("no physical printer available: %v", err)
		}
		log.Printf("[Printer] ERROR: Job %s (%s) failed — no target physical printer found (%s)", job.ID, job.FileName, reason)
		ps.failJob(job, reason)
		return
	}

	log.Printf("[Printer] Target physical printer selected for job %s (%s): '%s'", job.ID, job.FileName, targetPrinter)

	// Locate effective SumatraPDF executable: check configured path, then auto-discover
	if !isUsableSumatra(sumatraBin) {
		if discovered := ps.getFindSumatra()(); isUsableSumatra(discovered) {
			sumatraBin = discovered
			ps.setSumatraPath(discovered)
		} else {
			// Auto-heal on the fly: attempt standalone engine download if missing
			if provisioned, provErr := ps.getEnsureSumatra()(); provErr == nil && isUsableSumatra(provisioned) {
				sumatraBin = provisioned
				ps.setSumatraPath(provisioned)
			}
		}
	}

	ctx, cancel := context.WithTimeout(ps.ctx, ps.timeout)
	defer cancel()

	// 1. Detect exact document geometry (format, dimensions, paper size, orientation, page count)
	geom := DetectDocumentGeometry(job.FilePath)
	log.Printf("[Printer] Job %s geometry: format=%s, size=%.1fx%.1f pt, paper=%s, orientation=%s, pages=%d",
		job.ID, geom.Format, geom.WidthPt, geom.HeightPt, geom.PaperName, geom.Orientation, geom.PageCount)

	out, err := executePrint(ctx, sumatraBin, targetPrinter, job.FilePath, geom, job.Options)

	if errors.Is(ctx.Err(), context.DeadlineExceeded) {
		log.Printf("[Printer] ERROR: Job %s (%s) timed out after %v on target printer '%s'! Killing process...", job.ID, job.FileName, ps.timeout, targetPrinter)
		ps.failJob(job, "timeout exceeded")
		return
	}

	if err != nil {
		log.Printf("[Printer] ERROR: Job %s (%s) failed on target printer '%s': %v, out: %s", job.ID, job.FileName, targetPrinter, err, strings.TrimSpace(string(out)))
		ps.failJob(job, err.Error())
		return
	}

	// Printing succeeded! Clean up temp file from queue with fast progressive retry
	cleanupDelays := []time.Duration{25 * time.Millisecond, 50 * time.Millisecond, 100 * time.Millisecond, 200 * time.Millisecond, 400 * time.Millisecond}
	for _, delay := range cleanupDelays {
		if remErr := os.Remove(job.FilePath); remErr == nil || os.IsNotExist(remErr) {
			break
		}
		time.Sleep(delay)
	}
	log.Printf("[Printer] Job %s (%s) printed successfully to target printer '%s' and cleaned up.", job.ID, job.FileName, targetPrinter)
	if ps.OnJobCompleted != nil {
		ps.OnJobCompleted(job)
	}
}

func (ps *PrintService) moveToFailed(job PrintJob, reason string) {
	destPath := filepath.Join(ps.failedDir, job.ID)
	_ = os.Rename(job.FilePath, destPath)
	log.Printf("[Printer] Moved failed job %s to %s (reason: %s)", job.ID, destPath, reason)
}

